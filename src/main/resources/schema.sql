CREATE TABLE IF NOT EXISTS run_status (
    run_id          VARCHAR(512)  PRIMARY KEY,   -- executionArn
    source          VARCHAR(32)   NOT NULL,      -- STEP_FUNCTIONS | INFORMATICA
    job_id          VARCHAR(512)  NOT NULL,      -- stateMachineArn
    job_name        VARCHAR(256),
    run_name        VARCHAR(256),
    status          VARCHAR(32)   NOT NULL,
    started_at      TIMESTAMP WITH TIME ZONE,
    stopped_at      TIMESTAMP WITH TIME ZONE,
    error_code      VARCHAR(512),
    error_cause     VARCHAR(4000),
    redrive_count   INT           NOT NULL DEFAULT 0,
    failed_step     VARCHAR(256),                -- filled later by the enricher
    event_time      TIMESTAMP WITH TIME ZONE,    -- EventBridge event time
    observed_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Task-level detail for Informatica workflow runs (sessions, commands, worklets).
CREATE TABLE IF NOT EXISTS infa_task_run (
    run_id            VARCHAR(512) NOT NULL,       -- run_status.run_id of the workflow run
    instance_id       BIGINT       NOT NULL,
    worklet_run_id    BIGINT       NOT NULL,
    instance_name     VARCHAR(256),
    task_type         VARCHAR(64),
    status            VARCHAR(32),
    started_at        TIMESTAMP WITH TIME ZONE,
    stopped_at        TIMESTAMP WITH TIME ZONE,
    error_code        VARCHAR(64),
    error_msg         VARCHAR(4000),
    mapping_name      VARCHAR(256),
    src_success_rows  BIGINT,
    src_failed_rows   BIGINT,
    targ_success_rows BIGINT,
    targ_failed_rows  BIGINT,
    first_error_code  VARCHAR(64),
    first_error_msg   VARCHAR(4000),
    observed_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (run_id, instance_id, worklet_run_id)
);

-- Root cause of a failed / timed-out Step Functions execution, from its execution history.
CREATE TABLE IF NOT EXISTS run_failure_detail (
    run_id          VARCHAR(512) PRIMARY KEY,   -- run_status.run_id (execution ARN)
    failed_state    VARCHAR(256),               -- state that failed, e.g. "Load Loans"
    failure_event   VARCHAR(64),                -- TaskFailed, TaskTimedOut, ExecutionFailed, ...
    service         VARCHAR(64),                -- glue, lambda, ecs, batch, ...
    resource        VARCHAR(256),               -- e.g. startJobRun.sync
    service_job     VARCHAR(256),               -- Glue job name, when available
    service_run_id  VARCHAR(256),               -- Glue job run id / Lambda request id
    error           VARCHAR(512),               -- e.g. States.TaskFailed, Lambda.Unknown
    error_type      VARCHAR(256),               -- e.g. Lambda errorType
    message         VARCHAR(4000),              -- readable error from the service
    summary         VARCHAR(512),               -- one line: "glue job_x: AnalysisException: ..."
    attempts        INT,                        -- failures of that state (retries + 1)
    execution_error VARCHAR(512),               -- top-level ExecutionFailed error
    execution_cause VARCHAR(4000),
    task_cause      VARCHAR(8000),              -- raw cause from the task, for the LLM
    analysed_at     TIMESTAMP WITH TIME ZONE NOT NULL
);

-- How each downstream run relates to its upstream runs (one row per configured edge).
CREATE TABLE IF NOT EXISTS run_link (
    pipeline           VARCHAR(256) NOT NULL,
    downstream_node    VARCHAR(256) NOT NULL,
    downstream_run_id  VARCHAR(512) NOT NULL,
    upstream_node      VARCHAR(256) NOT NULL,
    upstream_run_id    VARCHAR(512),                 -- null when no upstream run was found
    state              VARCHAR(32)  NOT NULL,        -- OK | UPSTREAM_STILL_RUNNING | UPSTREAM_FAILED | NO_UPSTREAM_RUN
    lag_seconds        BIGINT,                       -- upstream end -> downstream start, when OK
    downstream_start   TIMESTAMP WITH TIME ZONE NOT NULL,
    alerted            BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (downstream_run_id, pipeline, upstream_node)
);

-- Dependency problems, raised once each (dedup on type + pipeline + node + run).
CREATE TABLE IF NOT EXISTS pipeline_alert (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type  VARCHAR(64)   NOT NULL,   -- UPSTREAM_FAILED | MISSING_TRIGGER | RAN_ON_...
    pipeline    VARCHAR(256)  NOT NULL,
    node_id     VARCHAR(256)  NOT NULL,
    run_id      VARCHAR(512)  NOT NULL,
    detail      VARCHAR(2000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    acknowledged BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_pipeline_alert UNIQUE (alert_type, pipeline, node_id, run_id)
);

CREATE INDEX IF NOT EXISTS ix_run_status_job ON run_status (job_id, started_at);
CREATE INDEX IF NOT EXISTS ix_run_status_name ON run_status (source, job_name, started_at);
CREATE INDEX IF NOT EXISTS ix_run_status_status ON run_status (status);
